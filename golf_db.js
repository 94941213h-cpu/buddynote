// 이름으로 검색 (부분 일치)
function searchGolfCourse(query) {
  if (!query || query.length < 1) return [];
  const q = query.toLowerCase().replace(/\s/g, '');
  return GOLF_DB.filter(c =>
    c.name.toLowerCase().replace(/\s/g, '').includes(q) ||
    c.region.replace(/\s/g, '').includes(q)
  ).slice(0, 8);
}
